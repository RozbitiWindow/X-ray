namespace XRay.Core.LargeFiles;

/// <summary>
/// Categories of files that may be worth reviewing. These are suggestions only: a category never means a file
/// is unnecessary or safe to delete.
/// </summary>
public enum ReviewCategory
{
    None,
    Installer,
    Archive,
    DiskImage,
    BuildOutput,
    Temporary,
    LargeLog,
    CrashDump,
    Backup,
}

/// <summary>A review suggestion with a human-readable reason.</summary>
public readonly record struct ReviewSuggestion(ReviewCategory Category, string Reason)
{
    public static ReviewSuggestion None { get; } = new(ReviewCategory.None, string.Empty);

    public bool IsSuggested => Category != ReviewCategory.None;
}

/// <summary>Heuristics that flag potentially interesting files based on name, extension, size and location.</summary>
public static class ReviewHeuristics
{
    /// <summary>Logs smaller than this are not flagged.</summary>
    public const long LargeLogThreshold = 10L * 1024 * 1024;

    private static readonly HashSet<string> InstallerExtensions = new(StringComparer.OrdinalIgnoreCase)
        { ".msi", ".msix", ".msixbundle", ".appx", ".appxbundle", ".msp" };

    private static readonly HashSet<string> ArchiveExtensions = new(StringComparer.OrdinalIgnoreCase)
        { ".zip", ".7z", ".rar", ".tar", ".gz", ".tgz", ".bz2", ".xz", ".zst", ".cab", ".lz", ".lzma" };

    private static readonly HashSet<string> DiskImageExtensions = new(StringComparer.OrdinalIgnoreCase)
        { ".iso", ".img", ".vhd", ".vhdx", ".vmdk", ".vdi", ".qcow2", ".dmg", ".wim", ".esd" };

    private static readonly HashSet<string> BuildPackageExtensions = new(StringComparer.OrdinalIgnoreCase)
        { ".apk", ".aab", ".ipa", ".nupkg", ".snupkg", ".xcarchive" };

    private static readonly HashSet<string> DumpExtensions = new(StringComparer.OrdinalIgnoreCase)
        { ".dmp", ".mdmp", ".hdmp" };

    private static readonly HashSet<string> LogExtensions = new(StringComparer.OrdinalIgnoreCase)
        { ".log", ".etl", ".evtx_old" };

    private static readonly HashSet<string> TempExtensions = new(StringComparer.OrdinalIgnoreCase)
        { ".tmp", ".temp", ".partial", ".crdownload", ".part" };

    private static readonly HashSet<string> BackupExtensions = new(StringComparer.OrdinalIgnoreCase)
        { ".bak", ".old", ".orig", ".backup", ".sav" };

    private static readonly HashSet<string> ProjectBuildSegments = new(StringComparer.OrdinalIgnoreCase)
        { "build", "builds", "dist", "out", "target" };

    private static readonly HashSet<string> EngineIntermediateSegments = new(StringComparer.OrdinalIgnoreCase)
        { "Intermediate", "DerivedData" };

    /// <summary>Returns a suggestion for the file at <paramref name="fullPath"/>, or <see cref="ReviewSuggestion.None"/>.</summary>
    public static ReviewSuggestion Evaluate(string fullPath, long size)
    {
        string name = Path.GetFileName(fullPath);
        string ext = Path.GetExtension(name);
        string[] segments = fullPath.Split(['\\', '/'], StringSplitOptions.RemoveEmptyEntries);

        // Windows-managed stores look like installers/archives but must never be cleaned up by hand.
        if (IsProtectedWindowsStore(segments))
        {
            return ReviewSuggestion.None;
        }

        if (DumpExtensions.Contains(ext) || HasSegment(segments, "CrashDumps"))
        {
            return new(ReviewCategory.CrashDump, "Crash dump - usually only needed when diagnosing a crash.");
        }

        if (InstallerExtensions.Contains(ext) ||
            (ext.Equals(".exe", StringComparison.OrdinalIgnoreCase) &&
             (HasSegment(segments, "Downloads") || ContainsAny(name, "setup", "install", "installer"))))
        {
            return new(ReviewCategory.Installer, "Installer package - often kept after the software is installed.");
        }

        if (DiskImageExtensions.Contains(ext))
        {
            return new(ReviewCategory.DiskImage, "Disk image - may be a leftover download or a virtual machine disk in use.");
        }

        if (BuildPackageExtensions.Contains(ext))
        {
            return new(ReviewCategory.BuildOutput, "Exported build package - older builds can usually be regenerated.");
        }

        if (IsInBuildFolder(segments))
        {
            return new(ReviewCategory.BuildOutput, "Located in a build output folder - typically regenerated by a rebuild.");
        }

        if (LogExtensions.Contains(ext) && size >= LargeLogThreshold)
        {
            return new(ReviewCategory.LargeLog, "Large log file - check whether the application still needs it.");
        }

        if (TempExtensions.Contains(ext) || name.StartsWith("~$", StringComparison.Ordinal) ||
            HasSegment(segments, "Temp") || HasSegment(segments, "tmp"))
        {
            return new(ReviewCategory.Temporary, "Temporary file or temp folder - may be in use by a running program.");
        }

        if (BackupExtensions.Contains(ext))
        {
            return new(ReviewCategory.Backup, "Backup copy - confirm a newer version exists before removing.");
        }

        if (ArchiveExtensions.Contains(ext))
        {
            return new(ReviewCategory.Archive, "Archive - its contents may already be extracted elsewhere.");
        }

        return ReviewSuggestion.None;
    }

    public static string DisplayName(ReviewCategory category) => category switch
    {
        ReviewCategory.Installer => "Installer",
        ReviewCategory.Archive => "Archive",
        ReviewCategory.DiskImage => "Disk image",
        ReviewCategory.BuildOutput => "Build output",
        ReviewCategory.Temporary => "Temporary",
        ReviewCategory.LargeLog => "Large log",
        ReviewCategory.CrashDump => "Crash dump",
        ReviewCategory.Backup => "Backup copy",
        _ => "-",
    };

    private static readonly HashSet<string> ProtectedWindowsFolders = new(StringComparer.OrdinalIgnoreCase)
        { "Installer", "WinSxS", "System32", "SysWOW64", "servicing", "assembly", "Microsoft.NET" };

    /// <summary>True for paths such as C:\Windows\Installer or C:\Windows\WinSxS.</summary>
    private static bool IsProtectedWindowsStore(string[] segments) =>
        segments.Length > 2 &&
        segments[1].Equals("Windows", StringComparison.OrdinalIgnoreCase) &&
        ProtectedWindowsFolders.Contains(segments[2]);

    private static bool HasSegment(string[] segments, string segment)
    {
        // The last segment is the file name itself.
        for (int i = 0; i < segments.Length - 1; i++)
        {
            if (segments[i].Equals(segment, StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }
        }

        return false;
    }

    private static bool IsInBuildFolder(string[] segments)
    {
        for (int i = 0; i < segments.Length - 1; i++)
        {
            string s = segments[i];
            if (s.Equals("obj", StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }

            // bin\Debug and bin\Release are typical .NET outputs; a bare "bin" is too ambiguous (e.g. Program Files).
            if (s.Equals("bin", StringComparison.OrdinalIgnoreCase) && i + 1 < segments.Length - 1 &&
                (segments[i + 1].Equals("Debug", StringComparison.OrdinalIgnoreCase) ||
                 segments[i + 1].Equals("Release", StringComparison.OrdinalIgnoreCase)))
            {
                return true;
            }

            if (s.Equals("node_modules", StringComparison.OrdinalIgnoreCase) && i + 1 < segments.Length - 1 &&
                segments[i + 1].Equals(".cache", StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }

            if (EngineIntermediateSegments.Contains(s))
            {
                return true;
            }

            // Generic names such as "build" or "dist" only count inside what looks like a source-code tree.
            if (ProjectBuildSegments.Contains(s) && IsProjectSibling(segments, i))
            {
                return true;
            }
        }

        return false;
    }

    // Heuristic: a build folder whose parent path contains a typical source-code location.
    private static bool IsProjectSibling(string[] segments, int index)
    {
        for (int i = 0; i < index; i++)
        {
            string s = segments[i];
            if (s.Equals("source", StringComparison.OrdinalIgnoreCase) ||
                s.Equals("repos", StringComparison.OrdinalIgnoreCase) ||
                s.Equals("src", StringComparison.OrdinalIgnoreCase) ||
                s.Equals("projects", StringComparison.OrdinalIgnoreCase) ||
                s.Equals("dev", StringComparison.OrdinalIgnoreCase) ||
                s.Equals("code", StringComparison.OrdinalIgnoreCase) ||
                s.Equals("git", StringComparison.OrdinalIgnoreCase) ||
                s.Equals("Unity", StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }
        }

        return false;
    }

    private static bool ContainsAny(string value, params string[] needles)
    {
        foreach (string n in needles)
        {
            if (value.Contains(n, StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }
        }

        return false;
    }
}
